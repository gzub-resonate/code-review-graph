"""Post-build jOOQ resolver for Java code.

jOOQ generates one ``Table`` class per database table (plus ``Record``, ``Pojo``,
``Dao`` and ``Routine`` classes and the ``Tables``/``Keys`` holders).  Callers use
them through static-imported constants (``ORDERS``), qualified constants
(``Tables.ORDERS``) and fluent chains (``dsl.insertInto(ORDERS)``).  The parser
sees one file at a time, so it leaves most of that as bare names, and several
generated classes share one simple name (``Orders`` is the table and the pojo).

This pass runs after the parse, like ``spring_resolver``, and does two things:

(a) Binds bare Java CALLS/REFERENCES edges to the generated node when the file's
    imports (or its own package) name exactly one generated class, when the
    receiver is a static-imported or qualified table constant, or when the
    receiver is typed as a generated class.  jOOQ library methods (``select``,
    ``where``, ``fetch``) have no node and stay bare.  A method name shared by
    several overloads binds to the first overload with ``jooq_overloads`` set to
    their count.  It also adds ``function -> Table class`` REFERENCES edges for
    table-constant use, because a field access (``ORDERS.ID``) is not an edge the
    parser writes.

(b) Links code that reads or writes a table to ``external:db-table:<schema>.<table>``
    with ``{"access": "read"|"write", "via": "jooq"}``: calls such as
    ``insertInto(T)`` / ``selectFrom(T)`` / ``.from(T)`` whose first argument is a
    table constant, and Dao/Record methods on a typed receiver.  Schema and table
    come from the generated class (``DSL.name("...")``, the schema class), else the
    snake_case class name with ``schema_inferred`` set.

Derived REFERENCES edges carry ``jooq_derived`` and are rebuilt on every run; the
in-place CALLS/REFERENCES rewrites carry ``jooq_resolved``.  Generated code is
recognised by the ``generated by jOOQ`` header, and no node is marked or
filtered here, so dead-code and hub rules keep their behaviour.
"""

