_IMPORT_RE = re.compile(r"^\s*import\s+(static\s+)?([\w.]+?)(\.\*)?\s*;", re.MULTILINE)
_PACKAGE_RE = re.compile(r"^\s*package\s+([\w.]+)\s*;", re.MULTILINE)
_GENERATED_MARKER = "generated by jOOQ"
_CONST_NEW_RE = re.compile(r"public\s+static\s+final\s+(\w+)\s+(\w+)\s*=\s*new\s+\1\s*\(")
_CONST_ALIAS_RE = re.compile(r"public\s+static\s+final\s+(\w+)\s+(\w+)\s*=\s*\w+\.\w+\s*;")
_TABLE_NAME_RE = re.compile(r'this\(\s*(?:DSL\.)?name\(\s*"([^"]+)"\s*\)\s*,\s*null')
_SUPER_NAME_RE = re.compile(r'super\(\s*(?:DSL\.)?name\(\s*"([^"]+)"\s*\)')
_SCHEMA_REF_RE = re.compile(r"getSchema\(\)\s*\{\s*return\s+[^;?]*\?\s*null\s*:\s*(\w+)\.\w+")
_SCHEMA_SUPER_RE = re.compile(r'super\(\s*"([^"]*)"')
_JAVADOC_TABLE_RE = re.compile(r"<code>(\w+)\.(\w+)</code>")
_SUPER_TABLE_RE = re.compile(r"super\(\s*(\w+)\s*\.\s*(\w+)")
_ALIAS_DECL_RE = re.compile(r"(?<![\w.])([A-Z]\w*)\s+(\w+)\s*=")
_CHAIN_RE = re.compile(r"\s*([A-Za-z_]\w*(?:\s*\.\s*[A-Za-z_]\w*)*)")
_QUALIFIED_CONST_RE = re.compile(r"(?<![\w.])([A-Za-z_]\w*)\s*\.\s*([A-Z_][A-Z0-9_]*)\b")
_CAMEL_RE = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


def _snake(name: str) -> str:
    return _CAMEL_RE.sub("_", name).lower()


def _blank(src: str) -> str:
    """Replace comments and string/char literals with spaces, keeping offsets and newlines."""
    out = list(src)
    i, n = 0, len(src)
    while i < n:
        two = src[i:i + 2]
        if two == "//":
            j = src.find("\n", i)
            j = n if j < 0 else j
        elif two == "/*":
            j = src.find("*/", i + 2)
            j = n if j < 0 else j + 2
        elif src.startswith('"""', i):
            j = src.find('"""', i + 3)
            j = n if j < 0 else j + 3
        elif src[i] in "\"'":
            quote, j = src[i], i + 1
            while j < n and src[j] != quote and src[j] != "\n":
                j += 2 if src[j] == "\\" else 1
            j = min(j + 1, n)
        else:
            i += 1
            continue
        for k in range(i, min(j, n)):
            if out[k] != "\n":
                out[k] = " "
        i = j
    return "".join(out)


class _Imports:
    """Imports and package of one Java file."""

    def __init__(self, text: str) -> None:
        self.package = ""
        match = _PACKAGE_RE.search(text)
        if match:
            self.package = match.group(1)
        self.explicit: dict[str, str] = {}
        self.wildcards: list[str] = []
        self.static_members: dict[str, str] = {}
        self.static_wildcards: list[str] = []
        for m in _IMPORT_RE.finditer(text):
            is_static, name, wildcard = bool(m.group(1)), m.group(2), bool(m.group(3))
            if is_static and wildcard:
                self.static_wildcards.append(name)
            elif is_static:
                owner, _, member = name.rpartition(".")
                self.static_members[member] = owner
            elif wildcard:
                self.wildcards.append(name)
            else:
                self.explicit[name.rpartition(".")[2]] = name


class _Gen:
    """The generated jOOQ classes of the graph."""

    def __init__(self) -> None:
        self.by_fqn: dict[str, str] = {}
        self.fqn_of: dict[str, str] = {}
        self.packages: set[str] = set()
        self.names_in_package: dict[tuple[str, str], str] = {}
        self.kind: dict[str, str] = {}
        self.consts: dict[tuple[str, str], str] = {}
        self.consts_by_owner: dict[str, dict[str, str]] = {}
        self.table_target: dict[str, tuple[str, bool]] = {}
        self.owner_table: dict[str, str] = {}
        self.methods: dict[tuple[str, str], list[str]] = {}


def _read(path: str, repo_root: Optional[Path]) -> Optional[str]:
    p = Path(path)
    if not p.is_absolute() and repo_root is not None:
        p = repo_root / p
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None


def _resolve_simple(
    name: str, imports: _Imports, gen: _Gen, own_classes: set[str],
    other_pkg_classes: set[tuple[str, str]],
) -> Optional[str]:
    """The generated class fqn a simple type name means in a file, else None.

    Java order: a type declared in the file, a single-type import, a type of the
    file's package, then on-demand imports (exactly one candidate must exist).
    """
    if name in own_classes:
        return None
    explicit = imports.explicit.get(name)
    if explicit is not None:
        return explicit if explicit in gen.by_fqn else None
    if (imports.package, name) in other_pkg_classes:
        fqn = f"{imports.package}.{name}" if imports.package else name
        return fqn if fqn in gen.by_fqn else None
    found = [f"{pkg}.{name}" for pkg in imports.wildcards if f"{pkg}.{name}" in gen.by_fqn]
    return found[0] if len(found) == 1 else None


def _build_gen(store: GraphStore, repo_root: Optional[Path]) -> _Gen:
    conn = store._conn
    gen = _Gen()
    header_cache: dict[str, Optional[str]] = {}
    texts: dict[str, str] = {}
    rows = conn.execute(
        "SELECT qualified_name, name, file_path, extra FROM nodes "
        "WHERE kind = 'Class' AND language = 'java'"
    ).fetchall()
    for row in rows:
        path = row["file_path"]
        if path not in header_cache:
            text = _read(path, repo_root)
            header_cache[path] = text if text and _GENERATED_MARKER in text[:600] else None
            if header_cache[path] is not None:
                texts[path] = header_cache[path]  # type: ignore[assignment]
        if header_cache[path] is None:
            continue
        try:
            package = (json.loads(row["extra"] or "{}")).get("java_package")
        except (json.JSONDecodeError, TypeError):
            package = None
        local = row["qualified_name"].split("::", 1)[-1]
        fqn = f"{package}.{local}" if package else local
        if fqn in gen.by_fqn:
            continue
        gen.by_fqn[fqn] = row["qualified_name"]
        gen.fqn_of[row["qualified_name"]] = fqn
        if package:
            gen.packages.add(package)
            gen.names_in_package[(package, local)] = fqn
        text = texts[path]
        head = re.search(rf"class\s+{re.escape(row['name'])}\b[^{{]*", text)
        decl = head.group(0) if head else ""
        if "TableImpl" in decl:
            gen.kind[fqn] = "table"
        elif re.search(r"extends\s+\w*Record\w*Impl|extends\s+TableRecordImpl", decl):
            gen.kind[fqn] = "record"
        elif "DAOImpl" in decl:
            gen.kind[fqn] = "dao"
        elif "AbstractRoutine" in decl:
            gen.kind[fqn] = "routine"
        else:
            gen.kind[fqn] = "other"
    for row in conn.execute(
        "SELECT name, qualified_name, parent_name, file_path FROM nodes "
        "WHERE kind = 'Function' AND language = 'java' AND parent_name IS NOT NULL"
    ).fetchall():
        if header_cache.get(row["file_path"]) is not None:
            class_qual = f"{row['file_path']}::{row['parent_name']}"
            gen.methods.setdefault((class_qual, row["name"]), []).append(row["qualified_name"])

    imports_of = {path: _Imports(text) for path, text in texts.items()}
    class_files = {gen.by_fqn[f]: f for f in gen.by_fqn}
    own_by_file: dict[str, set[str]] = {}
    for qual in class_files:
        own_by_file.setdefault(qual.split("::", 1)[0], set()).add(qual.split("::", 1)[1])
    pkg_names = set(gen.names_in_package)

    def resolve(path: str, name: str) -> Optional[str]:
        return _resolve_simple(name, imports_of[path], gen, set(), pkg_names)

    for fqn, qual in gen.by_fqn.items():
        path = qual.split("::", 1)[0]
        text = texts[path]
        kind = gen.kind[fqn]
        if kind == "table":
            for m in _CONST_NEW_RE.finditer(text):
                gen.consts[(fqn, m.group(2))] = fqn
        elif kind == "other":
            for m in _CONST_ALIAS_RE.finditer(text):
                target = resolve(path, m.group(1))
                if target and gen.kind.get(target) == "table":
                    gen.consts[(fqn, m.group(2))] = target
    for fqn, qual in gen.by_fqn.items():
        if gen.kind[fqn] != "table":
            continue
        path = qual.split("::", 1)[0]
        text = texts[path]
        simple = qual.split("::", 1)[1].rpartition(".")[2]
        table = None
        for rx in (_TABLE_NAME_RE, _SUPER_NAME_RE):
            m = rx.search(text)
            if m:
                table = m.group(1)
                break
        schema = None
        m = _SCHEMA_REF_RE.search(text)
        if m:
            schema_fqn = resolve(path, m.group(1))
            if schema_fqn:
                sm = _SCHEMA_SUPER_RE.search(texts[gen.by_fqn[schema_fqn].split("::", 1)[0]])
                if sm and sm.group(1):
                    schema = sm.group(1)
        if schema is None or table is None:
            jm = _JAVADOC_TABLE_RE.search(text)
            if jm:
                schema = schema or jm.group(1)
                table = table or jm.group(2)
        inferred = schema is None or table is None
        gen.table_target[fqn] = (
            f"{schema or 'public'}.{table or _snake(simple)}", inferred,
        )
    for (owner, const), table in gen.consts.items():
        gen.consts_by_owner.setdefault(owner, {})[const] = table
    # Record/Dao owner tables: super(Table.CONST) names a table constant.
    for fqn in [f for f, k in gen.kind.items() if k in ("record", "dao")]:
        path = gen.by_fqn[fqn].split("::", 1)[0]
        m = _SUPER_TABLE_RE.search(texts[path])
        if m:
            head = resolve(path, m.group(1))
            table = gen.consts.get((head, m.group(2))) if head else None
            if table:
                gen.owner_table[fqn] = table
            else:
                gen.owner_table.pop(fqn, None)
        else:
            gen.owner_table.pop(fqn, None)
    return gen


class _FileView:
    """What one Java file says about jOOQ tables."""

    def __init__(
        self, text: str, gen: _Gen, own_classes: set[str], owner_fqn: str = "",
    ) -> None:
        self.text = _blank(text)
        self.imports = _Imports(text)
        self.gen = gen
        self.own = own_classes
        self.pkg_names = set(gen.names_in_package)
        self.line_starts = [0] + [m.end() for m in re.finditer("\n", self.text)]
        self.static_consts: dict[str, str] = {}
        imp = self.imports
        for member, owner in imp.static_members.items():
            table = gen.consts.get((owner, member))
            if table:
                self.static_consts[member] = table
        for owner in imp.static_wildcards:
            for const, table in gen.consts_by_owner.get(owner, {}).items():
                self.static_consts.setdefault(const, table)
        if owner_fqn:
            for const, table in gen.consts_by_owner.get(owner_fqn, {}).items():
                self.static_consts.setdefault(const, table)
        self.aliases: dict[str, str] = {}
        for m in _ALIAS_DECL_RE.finditer(self.text):
            fqn = self.cls(m.group(1))
            if fqn and gen.kind.get(fqn) == "table":
                self.aliases[m.group(2)] = fqn

    def cls(self, name: str) -> Optional[str]:
        return _resolve_simple(name, self.imports, self.gen, self.own, self.pkg_names)

    def table_of(self, parts: list[str]) -> Optional[tuple[str, str]]:
        """``(table fqn, binding)`` for ``CONST``, ``Holder.CONST`` or ``pkg.Holder.CONST``."""
        if len(parts) == 1:
            if parts[0] in self.static_consts:
                return self.static_consts[parts[0]], "static_import"
            if parts[0] in self.aliases:
                return self.aliases[parts[0]], "alias"
            return None
        owner_fqn = (
            self.cls(parts[-2]) if len(parts) == 2 else ".".join(parts[:-1])
        )
        if owner_fqn and (owner_fqn, parts[-1]) in self.gen.consts:
            return self.gen.consts[(owner_fqn, parts[-1])], "qualified"
        return None

    def line_of(self, offset: int) -> int:
        return bisect.bisect_right(self.line_starts, offset)

    def statement_window(self, line: int) -> tuple[int, int]:
        """Offsets from the start of *line* to the end of its statement (``;`` at depth 0)."""
        start = self.line_starts[line - 1]
        depth = 0
        stop = min(len(self.text), start + 8000)
        for i in range(start, stop):
            ch = self.text[i]
            if ch in "({[":
                depth += 1
            elif ch in ")}]":
                depth -= 1
                if depth < 0:
                    return start, i
            elif ch == ";" and depth <= 0:
                return start, i
        return start, stop

    def first_arg_tables(
        self, line: int, name: str, receiver: Optional[str] = None,
    ) -> list[tuple[str, str]]:
        """Tables named by the first argument of each ``.name(`` call of the statement.

        The parser dates every call of a chain to the line the chain starts on, so
        the statement from *line* on is searched, not the line alone.
        """
        if not 1 <= line <= len(self.line_starts):
            return []
        start, end = self.statement_window(line)
        found: list[tuple[str, str]] = []
        for m in re.finditer(rf"(?<![\w$]){re.escape(name)}\s*\(", self.text[start:end]):
            before = self.text[:start + m.start()].rstrip()
            if not before.endswith("."):
                continue
            # Calls of one name can share a statement: the receiver the parser recorded
            # (or, for a chained call, a closing parenthesis) tells which one this is.
            prev = before[:-1].rstrip()
            if receiver:
                if not re.search(rf"(?<![\w.]){re.escape(receiver)}$", prev):
                    continue
            elif not prev.endswith((")", "]")):
                continue
            chain = _CHAIN_RE.match(self.text, start + m.end())
            if not chain:
                continue
            parts = [p.strip() for p in chain.group(1).split(".")]
            for k in range(len(parts), 0, -1):
                hit = self.table_of(parts[:k])
                if hit:
                    found.append(hit)
                    break
        return found

    def is_jooq_type(self, simple: str) -> bool:
        if simple in self.own:
            return False
        explicit = self.imports.explicit.get(simple)
        if explicit is not None:
            return explicit.startswith("org.jooq.")
        if any(w == "org.jooq" or w.startswith("org.jooq.") for w in self.imports.wildcards):
            return True
        return simple in _JOOQ_FALLBACK_TYPES

    def receiver_ok(self, extra: dict, arg_binding: str) -> bool:
        """Whether the receiver of an operation call can be a jOOQ query object."""
        declared = extra.get("receiver_type")
        receiver = extra.get("receiver")
        if not declared and receiver:
            if receiver == "DSL":
                return True
            m = re.search(
                rf"(?<![\w.])([A-Z]\w*)(?:<[^;=()]*>)?\s+{re.escape(str(receiver))}\s*[;=,)]",
                self.text,
            )
            declared = m.group(1) if m else None
            if declared is None:
                return arg_binding != "alias"
        if declared:
            return self.is_jooq_type(str(declared).split("<")[0])
        return True


_STATIC_FINAL_RE = re.compile(
    r"static\s+final\s+((?:[a-z]\w*\s*\.\s*)*[A-Z]\w*)\s+(\w+)\s*="
)


def _owner_fqn(path: str, text: str) -> str:
    package = _PACKAGE_RE.search(text)
    stem = Path(path).stem
    return f"{package.group(1)}.{stem}" if package else stem


def _collect_app_constants(gen: _Gen, node_rows: dict, repo_root: Optional[Path]) -> None:
    """Register ``static final <Table> NAME = ...`` constants of hand-written classes.

    Repositories often re-export a generated table under their own name
    (``static final Orders ORDERS_TABLE = Orders.ORDERS``) and static-import it.
    Only top-level classes named after their file are covered.
    """
    pkg_names = set(gen.names_in_package)
    for path in node_rows:
        text = _read(path, repo_root)
        if text is None or "static" not in text:
            continue
        matches = list(_STATIC_FINAL_RE.finditer(text))
        if not matches:
            continue
        imports = _Imports(text)
        owner = _owner_fqn(path, text)
        for m in matches:
            written = re.sub(r"\s+", "", m.group(1))
            if "." in written:
                fqn = written if written in gen.by_fqn else None
            else:
                fqn = _resolve_simple(written, imports, gen, set(), pkg_names)
            if fqn and gen.kind.get(fqn) == "table":
                gen.consts.setdefault((owner, m.group(2)), fqn)
                gen.consts_by_owner.setdefault(owner, {})[m.group(2)] = fqn


def _enclosing(spans: list[tuple[int, int, str]], line: int) -> Optional[str]:
    best: Optional[tuple[int, str]] = None
    for start, end, qual in spans:
        if start <= line <= end and (best is None or end - start < best[0]):
            best = (end - start, qual)
    return best[1] if best else None


def _rewrite(store: GraphStore, row, target: str, extra: dict, binding: str) -> None:
    extra[_RESOLVED_FLAG] = True
    extra["jooq_binding"] = binding
    store._conn.execute(
        "UPDATE edges SET target_qualified = ?, extra = ? WHERE id = ?",
        (target, json.dumps(extra), row["id"]),
    )


def resolve_jooq(store: GraphStore, repo_root: Optional[Path] = None) -> dict:
    """Bind jOOQ-generated calls to their nodes and link table access to its table."""
    conn = store._conn
    removed = conn.execute(
        "DELETE FROM edges WHERE kind = 'REFERENCES' AND extra LIKE ?",
        (f'%"{_DERIVED_FLAG}"%',),
    ).rowcount
    gen = _build_gen(store, repo_root)
    stats = {
        "generated_classes": len(gen.by_fqn), "calls_resolved": 0, "references_resolved": 0,
        "table_refs_added": 0, "table_links_added": 0, "overloads_bound": 0,
        "unresolved_table_args": 0, "stale_removed": removed,
    }
    if not gen.by_fqn:
        if removed:
            store.commit()
        return stats

    node_rows: dict[str, list] = {}
    for row in conn.execute(
        "SELECT qualified_name, kind, name, file_path, line_start, line_end FROM nodes "
        "WHERE language = 'java' AND kind IN ('Function', 'Test', 'Class')"
    ).fetchall():
        node_rows.setdefault(row["file_path"], []).append(row)

    _collect_app_constants(gen, node_rows, repo_root)
    link_sites: dict[tuple[str, str, str], list] = {}
    ref_sites: dict[tuple[str, str, str], int] = {}

    for path, nodes in node_rows.items():
        text = _read(path, repo_root)
        if text is None or "import" not in text and "package" not in text:
            continue
        own = {n["qualified_name"].split("::", 1)[1] for n in nodes if n["kind"] == "Class"}
        view = _FileView(
            text, gen, own | {o.rpartition(".")[2] for o in own}, _owner_fqn(path, text),
        )
        imp = view.imports
        if not (
            imp.package in gen.packages
            or any(i.rpartition(".")[0] in gen.packages for i in imp.explicit.values())
            or any(w in gen.packages for w in imp.wildcards)
            or view.static_consts
            or any(o.rpartition(".")[0] in gen.packages for o in imp.static_wildcards)
            or any(o.rpartition(".")[0] in gen.packages for o in imp.static_members.values())
        ):
            continue
        spans = [
            (n["line_start"], n["line_end"], n["qualified_name"])
            for n in nodes if n["kind"] != "Class"
        ] + [
            (n["line_start"], n["line_end"], n["qualified_name"])
            for n in nodes if n["kind"] == "Class"
        ]
        function_spans = [s for s in spans if "." in s[2].split("::", 1)[-1]] or spans

        rows = conn.execute(
            "SELECT id, kind, source_qualified, target_qualified, line, extra FROM edges "
            "WHERE file_path = ? AND kind IN ('CALLS', 'REFERENCES')",
            (path,),
        ).fetchall()
        for row in rows:
            raw_target = row["target_qualified"]
            # An earlier resolver may have written a path-qualified target for a method
            # the graph does not have; the settle pass turns it bare again later, so
            # both spellings name the same call here.
            qualified = "::" in raw_target
            if qualified and row["kind"] != "CALLS":
                continue
            target = raw_target.split("::", 1)[1].rpartition(".")[2] if qualified else raw_target
            try:
                extra = json.loads(row["extra"] or "{}")
            except (json.JSONDecodeError, TypeError):
                extra = {}
            if extra.get(_RESOLVED_FLAG):
                continue
            receiver, recv_type = extra.get("receiver"), extra.get("receiver_type")
            recv_cls: Optional[str] = None
            binding = ""
            if row["kind"] == "REFERENCES" or not receiver:
                if not qualified and target[:1].isupper() and (
                    row["kind"] == "REFERENCES" or not extra.get("receiver_type")
                ):
                    fqn = view.cls(target)
                    if fqn:
                        _rewrite(store, row, gen.by_fqn[fqn], extra, "import")
                        stats["references_resolved" if row["kind"] == "REFERENCES"
                              else "calls_resolved"] += 1
                        continue
            else:
                hit = view.table_of([receiver]) if re.fullmatch(r"\w+", str(receiver)) else None
                if hit:
                    recv_cls, binding = hit[0], "table_constant"
                elif str(receiver)[:1].isupper() and re.fullmatch(r"\w+", str(receiver)):
                    recv_cls, binding = view.cls(str(receiver)), "typed_receiver"
                if recv_cls is None and recv_type:
                    recv_cls, binding = view.cls(str(recv_type).split("<")[0]), "typed_receiver"
                    if recv_cls is None and isinstance(extra.get("java_type"), str):
                        jt = extra["java_type"]
                        recv_cls = jt if jt in gen.by_fqn else None
            # (a) the call itself
            if row["kind"] == "CALLS" and not qualified and recv_cls and recv_cls in gen.by_fqn:
                candidates = gen.methods.get((gen.by_fqn[recv_cls], target), [])
                if candidates:
                    if len(candidates) > 1:
                        # Overloads of one generated method: the call site does not say
                        # which, so the first is bound and the count is kept.
                        extra["jooq_overloads"] = len(candidates)
                        stats["overloads_bound"] += 1
                    _rewrite(store, row, sorted(candidates)[0], extra, binding)
                    stats["calls_resolved"] += 1
            if row["kind"] != "CALLS":
                continue
            # (b) table access
            access = table = via = None
            links: list[tuple[str, str, str]] = []
            if (
                recv_cls
                and gen.kind.get(recv_cls) in ("dao", "record")
                and recv_cls in gen.owner_table
            ):
                kind = gen.kind[recv_cls]
                reads = _DAO_READS if kind == "dao" else _RECORD_READS
                writes = _DAO_WRITES if kind == "dao" else _RECORD_WRITES
                if target in writes:
                    access = "write"
                elif target in reads or (kind == "dao" and target.startswith(("find", "fetch"))):
                    access = "read"
                if access:
                    table, via = gen.owner_table[recv_cls], kind
            elif not qualified and (target in _WRITE_OPS or target in _READ_OPS):
                hits = view.first_arg_tables(row["line"], target, receiver)
                access = "write" if target in _WRITE_OPS else "read"
                for hit in hits:
                    if view.receiver_ok(extra, hit[1]):
                        links.append((hit[0], hit[1], access))
                if not hits and _stale_constant_arg(view, row["line"], target):
                    stats["unresolved_table_args"] += 1
                access = None
            if access and table:
                links.append((table, via, access))
            for table, via, access in links:
                if table not in gen.table_target:
                    continue
                key = (row["source_qualified"], table, access)
                site = link_sites.setdefault(key, [row["line"], 0, via, path])
                site[0] = min(site[0], row["line"])
                site[1] += 1

        # (a) table-constant use is a reference to the Table class
        spans_for_refs = function_spans
        names = set(view.static_consts)
        for m in re.finditer(r"(?<![\w.])([A-Z_][A-Z0-9_]*)\b(?!\s*\()", view.text):
            if m.group(1) in names:
                _note_ref(
                    view, spans_for_refs, ref_sites, path, m.start(),
                    view.static_consts[m.group(1)],
                )
        for m in _QUALIFIED_CONST_RE.finditer(view.text):
            hit = view.table_of([m.group(1), m.group(2)])
            if hit and hit[1] == "qualified":
                _note_ref(view, spans_for_refs, ref_sites, path, m.start(), hit[0])

    added_refs = 0
    for (source, table_fqn, path), line in ref_sites.items():
        store.upsert_edge(EdgeInfo(
            kind="REFERENCES", source=source, target=gen.by_fqn[table_fqn], file_path=path,
            line=line,
            extra={
                _DERIVED_FLAG: True, "use_form": "member", "via": "jooq",
                "jooq_binding": "table_constant", "confidence": 0.9,
                "confidence_tier": "INFERRED",
            },
        ))
        added_refs += 1
    added_links = 0
    for (source, table_fqn, access), (line, sites, via, path) in link_sites.items():
        target, inferred = gen.table_target[table_fqn]
        extra = {
            _DERIVED_FLAG: True, "access": access, "via": "jooq", "jooq_binding": via,
            "sites": sites, "table_class": gen.by_fqn[table_fqn].split("::", 1)[1],
            "confidence": 0.9 if via in ("static_import", "qualified") else 0.8,
            "confidence_tier": "INFERRED",
        }
        if inferred:
            extra["schema_inferred"] = True
        # upsert_edge folds edges sharing kind, source, target and line; a read and a
        # write of one table on one line are two accesses.
        extra["source_offset"] = 1 if access == "write" else 0
        store.upsert_edge(EdgeInfo(
            kind="REFERENCES", source=source, target=DB_TABLE_PREFIX + target,
            file_path=path, line=line, extra=extra,
        ))
        added_links += 1
    stats["table_refs_added"] = added_refs
    stats["table_links_added"] = added_links
    store.commit()
    logger.info(
        "jOOQ resolver: %d generated classes, %d calls and %d references bound, "
        "%d table references, %d table links", stats["generated_classes"],
        stats["calls_resolved"], stats["references_resolved"], added_refs, added_links,
    )
    return stats


def _note_ref(view, spans, ref_sites, path, offset, table_fqn) -> None:
    line = view.line_of(offset)
    source = _enclosing(spans, line)
    if source:
        key = (source, table_fqn, path)
        ref_sites[key] = min(ref_sites.get(key, line), line)


def _stale_constant_arg(view: _FileView, line: int, name: str) -> bool:
    """Whether an operation call's first argument is a constant imported from a generated
    class that does not declare it (generated sources out of date with the code)."""
    if not 1 <= line <= len(view.line_starts):
        return False
    start, end = view.statement_window(line)
    m = re.search(rf"\.\s*{re.escape(name)}\s*\(\s*([A-Za-z_]\w*)\b", view.text[start:end])
    if not m:
        return False
    owner = view.imports.static_members.get(m.group(1))
    return bool(owner) and owner in view.gen.by_fqn and m.group(1) not in view.static_consts
