def test_static_import_constant_binds_to_generated_method(tmp_path: Path) -> None:
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/OrderRepo.java": REPO})
    as_edges = [
        e for e in _edges(store, "OrderRepo.rename") if e["extra"].get("receiver") == "ORDERS"
    ]
    assert len(as_edges) == 1
    target = as_edges[0]["target_qualified"]
    assert target.endswith("tables/Orders.java::Orders.as")
    assert as_edges[0]["extra"]["jooq_binding"] == "table_constant"
    assert store._conn.execute(
        "SELECT 1 FROM nodes WHERE qualified_name = ?", (target,)
    ).fetchone()


def test_table_column_reference_links_function_to_table_class(tmp_path: Path) -> None:
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/OrderRepo.java": REPO})
    refs = [
        e for e in _edges(store, "OrderRepo.find", "REFERENCES")
        if e["extra"].get("jooq_derived") and not e["target_qualified"].startswith("external:")
    ]
    assert len(refs) == 1
    assert refs[0]["target_qualified"].endswith("tables/Orders.java::Orders")


def test_select_from_is_read_and_insert_into_is_write(tmp_path: Path) -> None:
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/OrderRepo.java": REPO})
    find = _table_links(store, "OrderRepo.find")
    assert [(e["target_qualified"], e["extra"]["access"], e["extra"]["via"]) for e in find] == [
        ("external:db-table:sales.orders", "read", "jooq")
    ]
    add = _table_links(store, "OrderRepo.add")
    assert [(e["target_qualified"], e["extra"]["access"]) for e in add] == [
        ("external:db-table:sales.orders", "write")
    ]
    assert "schema_inferred" not in add[0]["extra"]
    # an alias variable and a Holder.CONST argument both resolve
    assert _table_links(store, "OrderRepo.rename")[0]["extra"]["access"] == "write"
    assert _table_links(store, "OrderRepo.drop")[0]["extra"]["access"] == "write"


