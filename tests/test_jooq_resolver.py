def test_generated_class_resolves_to_its_node_by_import(tmp_path: Path) -> None:
    source = (
        "package com.acme.shop.web;\n"
        "import com.acme.shop.model.tables.pojos.Orders;\n"
        "public class Mapper {\n"
        "  public Object make() { Orders o = new Orders(); return o.getId(); }\n"
        "}\n"
    )
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/Mapper.java": source})
    targets = {e["target_qualified"] for e in _edges(store, "Mapper.make")}
    assert any(t.endswith("pojos/Orders.java::Orders") for t in targets)
    assert any(t.endswith("pojos/Orders.java::Orders.getId") for t in targets)
    assert not any(t.endswith("tables/Orders.java::Orders") for t in targets)


def test_unknown_constant_is_flagged_not_dropped(tmp_path: Path) -> None:
    source = (
        "package com.acme.shop.web;\n"
        "import static com.acme.shop.model.Tables.MISSING;\n"
        "import org.jooq.DSLContext;\n"
        "public class Odd {\n"
        "  private DSLContext dsl;\n"
        "  public void go() { dsl.insertInto(MISSING).execute(); }\n"
        "}\n"
    )
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/Odd.java": source})
    calls = _edges(store, "Odd.go")
    assert any(e["target_qualified"] == "insertInto" for e in calls)
    assert _table_links(store, "Odd.go") == []
    assert resolve_jooq(store)["unresolved_table_args"] == 1


def test_rerun_is_idempotent(tmp_path: Path) -> None:
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/OrderRepo.java": REPO})
    before = store._conn.execute("SELECT COUNT(*) FROM edges").fetchone()[0]
    resolve_jooq(store)
    resolve_jooq(store)
    assert store._conn.execute("SELECT COUNT(*) FROM edges").fetchone()[0] == before


def test_dao_style_record_method_links_table(tmp_path: Path) -> None:
    source = (
        "package com.acme.shop.web;\n"
        "import com.acme.shop.model.tables.records.OrdersRecord;\n"
        "public class Saver {\n"
        "  public void save(OrdersRecord rec) { rec.store(); rec.refresh(); }\n"
        "}\n"
    )
    store = _build(tmp_path, {"src/main/java/com/acme/shop/web/Saver.java": source})
    accesses = sorted(e["extra"]["access"] for e in _table_links(store, "Saver.save"))
    assert accesses == ["read", "write"]
