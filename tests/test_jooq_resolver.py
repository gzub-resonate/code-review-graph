def _build(tmp_path: Path, extra: dict[str, str]) -> GraphStore:
    for relative, source in {**FILES, **extra}.items():
        path = tmp_path / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")
    store = GraphStore(str(tmp_path / "graph.db"))
    full_build(tmp_path, store)
    run_post_processing(store)
    return store


def _edges(store: GraphStore, source_suffix: str, kind: str = "CALLS") -> list[dict]:
    rows = store._conn.execute(
        "SELECT target_qualified, line, extra FROM edges WHERE kind = ? "
        "AND source_qualified LIKE ?",
        (kind, f"%::{source_suffix}"),
    ).fetchall()
    return [{**dict(r), "extra": json.loads(r["extra"] or "{}")} for r in rows]


def _table_links(store: GraphStore, source_suffix: str) -> list[dict]:
    return [
        e for e in _edges(store, source_suffix, "REFERENCES")
        if e["target_qualified"].startswith("external:db-table:")
    ]


